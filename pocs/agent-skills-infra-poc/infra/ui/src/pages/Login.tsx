import { useForm } from "@tanstack/react-form";
import { useQuery } from "@tanstack/react-query";
import { useState } from "react";
import { fetchLocalCredentials, login } from "../api";
import { sortCredentials } from "../format";
import type { LocalCredential } from "../types";

export function Login({ onSignedIn }: { onSignedIn: () => void }) {
  const [error, setError] = useState<string | null>(null);
  const [revealed, setRevealed] = useState<string | null>(null);
  const credentials = useQuery({ queryKey: ["local-credentials"], queryFn: fetchLocalCredentials, retry: false });

  const signIn = async (clientId: string, clientSecret: string) => {
    setError(null);
    try {
      await login(clientId.trim(), clientSecret.trim());
      onSignedIn();
    } catch (e) {
      setError(e instanceof Error ? e.message : "sign in failed");
    }
  };

  const form = useForm({
    defaultValues: { clientId: "infra-admin", clientSecret: "" },
    onSubmit: ({ value }) => signIn(value.clientId, value.clientSecret),
  });

  const use = (c: LocalCredential) => {
    form.setFieldValue("clientId", c.client_id);
    form.setFieldValue("clientSecret", c.client_secret);
    void signIn(c.client_id, c.client_secret);
  };

  return (
    <div className="login">
      <div className="login-card">
        <div className="brand-mark">AI</div>
        <h1>Agent Infra Console</h1>
        <p className="muted">
          Sign in with any OAuth 2 client. The client credentials grant returns a Bearer token with the client's scopes. It
          stays in this tab only.
        </p>
        <form
          onSubmit={(e) => {
            e.preventDefault();
            void form.handleSubmit();
          }}
        >
          <form.Field
            name="clientId"
            validators={{ onChange: ({ value }) => (value.trim() ? undefined : "client id is required") }}
          >
            {(field) => (
              <label>
                Client id
                <input autoComplete="username" value={field.state.value} onChange={(e) => field.handleChange(e.target.value)} />
                {field.state.meta.errors.length > 0 && <span className="field-error">{field.state.meta.errors.join(", ")}</span>}
              </label>
            )}
          </form.Field>
          <form.Field
            name="clientSecret"
            validators={{ onChange: ({ value }) => (value.trim() ? undefined : "client secret is required") }}
          >
            {(field) => (
              <label>
                Client secret
                <input
                  type="password"
                  autoComplete="current-password"
                  value={field.state.value}
                  onChange={(e) => field.handleChange(e.target.value)}
                />
                {field.state.meta.errors.length > 0 && <span className="field-error">{field.state.meta.errors.join(", ")}</span>}
              </label>
            )}
          </form.Field>
          {error && <div className="alert">{error}</div>}
          <form.Subscribe selector={(s) => s.isSubmitting}>
            {(submitting) => (
              <button type="submit" disabled={submitting}>
                {submitting ? "Signing in" : "Sign in"}
              </button>
            )}
          </form.Subscribe>
        </form>
      </div>

      <aside className="creds">
        <h2>Local OAuth clients</h2>
        <p className="muted">
          Generated by <code>agentinfra bootstrap</code> and read from <code>infra/.secrets</code> by the local dev server.
          Click a client to sign in as it. <b>infra-admin</b> sees every tenant; a skill or MCP client sees only its own runs.
        </p>
        {credentials.isPending && <p className="muted">Loading clients</p>}
        {credentials.isError && <div className="alert">{credentials.error.message}</div>}
        <ul>
          {sortCredentials(credentials.data ?? []).map((c) => (
            <li key={c.client_id} className={`cred kind-${c.kind}`}>
              <div className="cred-head">
                <b className="mono">{c.client_id}</b>
                <span className={`kind kind-${c.kind}`}>{c.kind}</span>
                <button className="use" onClick={() => use(c)}>
                  Sign in
                </button>
              </div>
              <p className="cred-desc">{c.description}</p>
              <div className="cred-secret">
                <span className="mono">{revealed === c.client_id ? c.client_secret : "•".repeat(18)}</span>
                <button className="ghost tiny" onClick={() => setRevealed(revealed === c.client_id ? null : c.client_id)}>
                  {revealed === c.client_id ? "hide" : "show"}
                </button>
                <button className="ghost tiny" onClick={() => void navigator.clipboard?.writeText(c.client_secret)}>
                  copy
                </button>
              </div>
              <div className="chips">
                {c.scopes.map((s) => (
                  <span key={s} className="chip">
                    {s}
                  </span>
                ))}
              </div>
            </li>
          ))}
        </ul>
      </aside>
    </div>
  );
}
