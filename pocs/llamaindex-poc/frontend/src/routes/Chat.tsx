import { useMutation, useQuery } from "@tanstack/react-query";
import { useState } from "react";
import { api } from "../api";
import { DocumentPicker } from "../components/DocumentPicker";
import { Sources } from "../components/Sources";
import type { ChatResponse, Source } from "../types";

interface Turn {
  role: "user" | "assistant";
  content: string;
  sources?: Source[];
  elapsed?: number;
}

export function Chat() {
  const [turns, setTurns] = useState<Turn[]>([]);
  const [question, setQuestion] = useState("");
  const [topK, setTopK] = useState(5);
  const [docIds, setDocIds] = useState<string[]>([]);

  const documents = useQuery({ queryKey: ["documents"], queryFn: api.documents });

  const send = useMutation<ChatResponse, Error, string>({
    mutationFn: (asked) =>
      api.chat({
        question: asked,
        history: turns.map((turn) => ({ role: turn.role, content: turn.content })),
        top_k: topK,
        doc_ids: docIds,
      }),
    onSuccess: (data) =>
      setTurns((current) => [
        ...current,
        {
          role: "assistant",
          content: data.answer,
          sources: data.sources,
          elapsed: data.elapsed_seconds,
        },
      ]),
  });

  const submit = (): void => {
    const asked = question.trim();
    if (!asked) return;
    setTurns((current) => [...current, { role: "user", content: asked }]);
    setQuestion("");
    send.mutate(asked);
  };

  return (
    <>
      <div className="card">
        <h2>Chat with your PDFs</h2>
        <p className="hint">
          Retrieval runs through the LlamaIndex vector index; the answer is generated by the local
          Ollama model with the retrieved passages as context.
        </p>
        <DocumentPicker
          documents={documents.data?.documents ?? []}
          selected={docIds}
          onChange={setDocIds}
        />
        <div className="row" style={{ marginTop: 10 }}>
          <label className="muted">top_k</label>
          <input
            type="number"
            min={1}
            max={20}
            value={topK}
            style={{ width: 80 }}
            onChange={(event) => setTopK(Number(event.target.value))}
          />
          <button onClick={() => setTurns([])} disabled={turns.length === 0}>
            clear conversation
          </button>
        </div>
      </div>

      <div className="card">
        {turns.length === 0 && <p className="muted">Ask something about the indexed documents.</p>}
        {turns.map((turn, position) => (
          <div key={position} className={`bubble ${turn.role}`}>
            <div className="who">
              {turn.role}
              {turn.elapsed ? ` · ${turn.elapsed}s` : ""}
            </div>
            {turn.content}
            {turn.sources && <Sources sources={turn.sources} />}
          </div>
        ))}
        {send.isPending && <p className="muted">retrieving and generating…</p>}
        {send.isError && <div className="error">{send.error.message}</div>}

        <div className="row" style={{ marginTop: 12 }}>
          <input
            type="text"
            className="grow"
            value={question}
            placeholder="What does the runbook say about rollback?"
            onChange={(event) => setQuestion(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === "Enter") submit();
            }}
          />
          <button className="primary" onClick={submit} disabled={send.isPending || !question.trim()}>
            Ask
          </button>
        </div>
      </div>
    </>
  );
}
