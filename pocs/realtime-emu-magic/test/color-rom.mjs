export function colorRom() {
  const rom = Buffer.alloc(32768, 0)
  const code = [
    0x78, 0x18, 0xfb, 0xc2, 0x10, 0xa2, 0xff, 0x1f, 0x9a, 0xe2, 0x20,
    0x9c, 0x00, 0x42, 0xa9, 0x80, 0x8d, 0x00, 0x21,
    0x9c, 0x05, 0x21, 0x9c, 0x2c, 0x21, 0x9c, 0x2d, 0x21,
    0xa9, 0x1f, 0x8d, 0x00, 0x00, 0x9c, 0x01, 0x00,
    0x9c, 0x10, 0x00,
    0xa9, 0x0f, 0x8d, 0x00, 0x21,
    0xad, 0x12, 0x42, 0x10, 0xfb,
    0xee, 0x10, 0x00,
    0x9c, 0x21, 0x21, 0xad, 0x00, 0x00, 0x8d, 0x22, 0x21,
    0xad, 0x01, 0x00, 0x8d, 0x22, 0x21,
    0xad, 0x12, 0x42, 0x30, 0xfb, 0x80, 0xe2
  ]
  rom.set(code)
  rom[0x100] = 0x40
  rom.write('FANTASY GAME         ', 0x7fc0, 'ascii')
  rom.set([0x20, 0x00, 0x05, 0x00, 0x01, 0x00, 0x00], 0x7fd5)
  for (const offset of [0x7fea, 0x7fee, 0x7ffa, 0x7ffe]) rom.writeUInt16LE(0x8100, offset)
  rom.writeUInt16LE(0x8000, 0x7ffc)
  rom.writeUInt16LE(0xffff, 0x7fdc)
  const sum = rom.reduce((total, byte) => total + byte, 0) & 0xffff
  rom.writeUInt16LE(sum ^ 0xffff, 0x7fdc)
  rom.writeUInt16LE(sum, 0x7fde)
  return rom
}
