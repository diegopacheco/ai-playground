function arches(s, grow, lift = 0.04, square = false) {
  const hz = s.wheelbase / 2;
  return [-hz, hz].map((z) => ({ z, y: s.wheelR + lift, r: s.wheelR + grow, square }));
}

function doorGaps(b, xAbs, zs, y0, y1) {
  for (const z of zs) b.side([[z - 0.004, y0], [z - 0.004, y1], [z + 0.004, y1], [z + 0.004, y0]], xAbs + 0.003, 'gap');
}

function handles(b, xAbs, zs, y) {
  b.both((s) => zs.forEach((z) => b.rbox(0.03, 0.035, 0.15, 0.012, 'chrome', s * (xAbs + 0.012), y, z)));
}

function mirrors(b, xAbs, y, z, big = false) {
  b.both((s) => {
    b.box(0.14, 0.04, 0.05, 'trim', s * (xAbs + 0.06), y - 0.05, z);
    b.rbox(0.07, big ? 0.24 : 0.17, big ? 0.2 : 0.15, 0.03, 'trim', s * (xAbs + 0.15), y + 0.03, z);
    b.box(0.005, big ? 0.2 : 0.14, big ? 0.16 : 0.11, 'glass', s * (xAbs + 0.185), y + 0.03, z - 0.01);
  });
}

function tailLamps(b, xAbs, y, z, w, h) {
  b.both((s) => {
    b.rbox(w + 0.03, h + 0.03, 0.04, 0.015, 'trim', s * xAbs, y, z);
    b.rbox(w, h, 0.05, 0.015, 'tail', s * xAbs, y, z - 0.008);
  });
}

function bumper(b, w, y, z, dir, hooks = true) {
  b.rbox(w, 0.24, 0.28, 0.04, 'trim', 0, y, z);
  b.box(w * 0.5, 0.04, 0.5, 'trim', 0, y - 0.15, z - dir * 0.22, dir * 0.15);
  if (hooks) b.both((s) => b.torus(0.045, 0.015, 'red', s * w * 0.28, y + 0.02, z + dir * 0.16, 0, Math.PI / 2, 0));
}

function spare(b, R, x, y, z, flat = false) {
  const rx = flat ? 0 : Math.PI / 2;
  b.cyl(R, R, 0.28, 'rubber', x, y, z, rx, 0, 0, 28);
  b.cyl(R * 0.56, R * 0.56, 0.3, 'rimLip', x, y, z, rx, 0, 0, 20);
  b.cyl(0.05, 0.05, 0.36, 'chrome', x, y, z, rx, 0, 0, 10);
}

