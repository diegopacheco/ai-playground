static const Glyph *find_glyph(char ch)
{
    char upper = (char)toupper((unsigned char)ch);
    for (size_t i = 0; i < sizeof glyphs / sizeof glyphs[0]; i++) {
        if (glyphs[i].ch == upper) {
            return &glyphs[i];
        }
    }
    return NULL;
}

static void draw_glyph(Framebuffer *fb, int x, int y, const Glyph *glyph, int scale, uint8_t color)
{
    for (int row = 0; row < FONT_GLYPH_H; row++) {
        for (int col = 0; col < FONT_GLYPH_W; col++) {
            if ((glyph->rows[row] >> (FONT_GLYPH_W - 1 - col)) & 1) {
                fb_fill_rect(fb, x + col * scale, y + row * scale, scale, scale, color);
            }
        }
    }
}

void font_draw(Framebuffer *fb, int x, int y, const char *text, int scale, uint8_t color)
{
    for (int cursor = x; *text != '\0'; text++, cursor += (FONT_GLYPH_W + 1) * scale) {
        const Glyph *glyph = find_glyph(*text);
        if (glyph != NULL) {
            draw_glyph(fb, cursor, y, glyph, scale, color);
        }
    }
}

void font_draw_shadow(Framebuffer *fb, int x, int y, const char *text, int scale, uint8_t color, uint8_t shadow)
{
    font_draw(fb, x + scale, y + scale, text, scale, shadow);
    font_draw(fb, x, y, text, scale, color);
}

void font_draw_centered(Framebuffer *fb, int y, const char *text, int scale, uint8_t color, uint8_t shadow)
{
    font_draw_shadow(fb, (SCREEN_W - font_width(text, scale)) / 2, y, text, scale, color, shadow);
}

int font_width(const char *text, int scale)
{
    int length = (int)strlen(text);
    return length == 0 ? 0 : length * (FONT_GLYPH_W + 1) * scale - scale;
}
